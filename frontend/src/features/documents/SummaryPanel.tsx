import { useState } from 'react';
import styles from './SummaryPanel.module.css';
import { Button } from '../../components/Button/Button';
import type { LexiGuardApi } from '../../api/index';
import type { DocumentCard, SummaryKeyPoint, SummaryResponse } from '../../api/contracts';
import { ApiError } from '../../api/errors';

interface SummaryPanelProps {
  api: LexiGuardApi;
  document: DocumentCard;
  onOpenSourceView: (page: number, quote?: string) => void;
}

function KeyPointCard({
  kp,
  onOpenPage,
}: {
  kp: SummaryKeyPoint;
  onOpenPage: (page: number) => void;
}) {
  return (
    <div className={styles.keyPointCard}>
      <div className={styles.keyPointLabel}>{kp.label}</div>
      <p className={styles.keyPointValue}>{kp.value}</p>
      {kp.page_refs && kp.page_refs.length > 0 && (
        <div className={styles.pageRefs}>
          {kp.page_refs.map((pg, i) => (
            <button
              key={i}
              type="button"
              className={styles.pageRefBadge}
              onClick={() => onOpenPage(pg)}
            >
              Page {pg}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

export function SummaryPanel({ api, document, onOpenSourceView }: SummaryPanelProps) {
  const [summary, setSummary] = useState<SummaryResponse | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const handleGenerate = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await api.summarizeDocument(document.document_id);
      setSummary(res);
    } catch (err) {
      if (err instanceof ApiError) {
        setError(err.userMessage);
      } else {
        setError('Could not generate summary. Please try again.');
      }
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className={styles.container}>
      {/* Header */}
      <div className={styles.header}>
        <div className={styles.headerLeft}>
          <h2 className={styles.title}>Document Summary</h2>
          <p className={styles.desc}>
            AI-generated overview extracted from document text using local Gemma inference.
            All processing is strictly on-device — no external network calls.
          </p>
        </div>
        <Button
          variant="primary"
          onClick={handleGenerate}
          disabled={loading}
          loading={loading}
        >
          {loading ? 'Generating…' : summary ? '↻ Regenerate' : '✦ Generate Summary'}
        </Button>
      </div>

      {error && (
        <div className="error-banner" role="alert">
          <span aria-hidden="true">⚠</span>
          <span>{error}</span>
          <Button variant="ghost" size="sm" onClick={handleGenerate}>Retry</Button>
        </div>
      )}

      {!summary && !loading && !error && (
        <div className={styles.emptyState}>
          <span className={styles.emptyIcon}>🔍</span>
          <p>Click <strong>Generate Summary</strong> to create an AI-powered overview of this document.</p>
          <p className={styles.emptyNote}>
            Gemma will extract parties, dates, obligations, critical clauses, and notable risks
            using only the document text — no outside knowledge.
          </p>
        </div>
      )}

      {loading && !summary && (
        <div className={styles.loadingState}>
          <div className={styles.spinner} />
          <p>Analysing document with local Gemma…</p>
        </div>
      )}

      {summary && (
        <>
          {/* Model / fallback indicator */}
          <div className={styles.metaRow}>
            <span className={styles.modelBadge}>
              {summary.fallback ? '⚡ Extractive (Gemma unavailable)' : `✦ ${summary.model_used}`}
            </span>
            {summary.referenced_pages.length > 0 && (
              <span className={styles.pagesNote}>
                Referenced: Pages {summary.referenced_pages.join(', ')}
              </span>
            )}
          </div>

          {/* Structured key points */}
          {summary.key_points && summary.key_points.length > 0 ? (
            <div className={styles.keyPointsGrid}>
              {summary.key_points.map((kp, i) => (
                <KeyPointCard
                  key={i}
                  kp={kp}
                  onOpenPage={(pg) => onOpenSourceView(pg)}
                />
              ))}
            </div>
          ) : (
            /* Full markdown fallback if key_points not parsed */
            <div className={styles.markdownBlock}>
              <pre className={styles.markdownPre}>{summary.summary_markdown}</pre>
            </div>
          )}

          <p className="legal-caveat" style={{ marginTop: 'var(--space-2)' }}>
            This summary is generated by an automated tool and does not constitute legal advice.
            Always verify important terms with a qualified legal professional.
          </p>
        </>
      )}
    </div>
  );
}
